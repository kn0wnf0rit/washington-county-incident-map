NONINJ_RE = re.compile(r'NON[ -]?INJURY|UNKNOWN INJURY|UKNOWN INJURY')
_cache = {}
def severity(ev):
    if ev in _cache: return _cache[ev]
    e = ev.strip().upper()
    if e in CRIT: s = 3
    elif e in HIGH: s = 2
    elif e in LOW: s = 0
    elif e in MED: s = 1
    elif e == 'FIRE DRILL': s = 0
    elif re.match(r'^(V/W|W/W|VW|WW|CITE|CIT/|TZD)', e): s = 0
    elif NONINJ_RE.search(e): s = 2
    elif LOW_RE.search(e) and not CRIT_RE.search(e): s = 0
    elif CRIT_RE.search(e): s = 3
    elif FIRE_RE.search(e) and 'ALARM' not in e and 'WORKS' not in e and 'PERMIT' not in e and 'BURN' not in e: s = 3
    elif HIGH_RE.search(e): s = 2
    else: s = 1
    _cache[ev] = s
    return s

if __name__ == '__main__':
    import json, collections
    items = json.load(open('event_counts.json'))
    by = collections.defaultdict(list); tot = collections.Counter()
    for k, v in items:
        s = severity(k); by[s].append((k, v)); tot[s] += v
    for s in (3, 2, 1, 0):
        print(f'=== sev {s}: {len(by[s])} labels, {tot[s]} incidents')
